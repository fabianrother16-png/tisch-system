export function translate(lang, code, vars = {}) {
  const dict = MESSAGES[lang] || MESSAGES.de;
  const text = dict[code] ?? MESSAGES.de[code] ?? code;
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// Wandelt { error: code, vars } in { error: Text, code } um.
export function localize(res, lang) {
  if (!res || !res.error) return res;
  const { error, vars, ...rest } = res;
  return { ...rest, error: translate(lang, error, vars), code: error };
}
